"""Generate C++ FT8 constants from the repository's protocol tables (GPLv3)."""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
out = ['// Generated by tools/Generate-Ft8NativeTables.py; WSJT-X protocol data, GPLv3.',
       '#ifndef WSJT_FT8_NATIVE_TABLES_HPP', '#define WSJT_FT8_NATIVE_TABLES_HPP',
       '#include <cstdint>', 'namespace ft8_native { namespace tables {']
for suffix, source in [('standard', 'lib/ft8/ldpc_174_91_c_parity.f90'),
                       ('parallel', 'lib/ft8var/ldpc_174_91_c_reordered_parity.f90')]:
    text = (root / source).read_text()
    values = {}
    for name, rows, width in [('Mn', 174, 3), ('Nm', 83, 7), ('nrw', 83, 1)]:
        match = re.search(r'\bdata\s+' + name + r'\s*/(.*?)/', text, re.S | re.I)
        numbers = [int(n) for n in re.findall(r'\d+', match.group(1))]
        assert len(numbers) == rows * width, (source, name, len(numbers))
        values[name] = numbers
        declaration = f'static int const {name}_{suffix}[{rows}]'
        if width > 1:
            declaration += f'[{width}]'
        out.append(declaration + ' = {')
        for row in range(rows):
            numbers_row = numbers[row * width:(row + 1) * width]
            if width > 1:
                out.append('  {' + ', '.join(str(v - 1) for v in numbers_row) + '},')
            else:
                out.append(f'  {numbers_row[0]},')
        out.append('};')
    for check in range(83):
        for bit in values['Nm'][check * 7:check * 7 + values['nrw'][check]]:
            assert check + 1 in values['Mn'][(bit - 1) * 3:bit * 3]
generator = re.findall(r'"([0-9a-fA-F]{23})"', (root / 'lib/ft8/ldpc_174_91_c_generator.f90').read_text())
assert len(generator) == 83
out.append('static std::uint64_t const generator[83][2] = {')
for row in generator:
    bits = ''.join(f'{int(c, 16):04b}' for c in row)[:91]
    masks = [sum((int(bits[j]) << (j % 64)) for j in range(start, stop))
             for start, stop in [(0, 64), (64, 91)]]
    out.append('  {' + ', '.join(f'0x{m:016x}ULL' for m in masks) + '},')
out += ['};', '}}', '#endif', '']
(root / 'lib/ft8/native/ft8_tables.hpp').write_text('\n'.join(out), encoding='utf-8')
